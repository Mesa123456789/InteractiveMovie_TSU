import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import { extname, join } from "node:path";

const kinds = {
  png: "image", jpg: "image", jpeg: "image", webp: "image", avif: "image",
  mp4: "video", webm: "video", mp3: "audio", wav: "audio", vtt: "subtitle",
};

async function scan(folder, segments = []) {
  const entries = await readdir(folder, { withFileTypes: true });
  const assets = await Promise.all(entries.map(async (entry) => {
    const parts = [...segments, entry.name];
    const path = join(folder, entry.name);
    if (entry.isDirectory()) return scan(path, parts);
    const kind = kinds[extname(entry.name).slice(1).toLowerCase()];
    if (!entry.isFile() || !kind) return [];
    return [{
      id: parts.join("/"),
      src: "/" + parts.map(encodeURIComponent).join("/"),
      kind,
      bytes: (await stat(path)).size,
    }];
  }));
  return assets.flat();
}

await mkdir("public", { recursive: true });
await mkdir("src/data", { recursive: true });
const assets = (await scan("public")).sort((a, b) => a.id.localeCompare(b.id, "en"));
await writeFile("src/data/assets.generated.ts", [
  "// Generated by npm run assets. Edit asset-mapping.ts to assign production media.",
  'import type { Asset } from "@/types/movie";',
  "export const assets = " + JSON.stringify(assets, null, 2) + " as const satisfies readonly Asset[];",
  "",
].join("\n"));
console.log(`Catalogued ${assets.length} assets.`);
