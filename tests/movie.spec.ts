test("word tiles support pointer placement, keyboard placement and reordering", async ({ page }) => {
  await seed(page, "g3");
  await page.goto("/watch");
  await page.locator(".word-bank").getByRole("button", { name: /我/ }).dragTo(page.locator(".sentence-slot").first(), { steps: 10 });
  await expect(page.locator(".sentence-slot").nth(0)).toContainText("我");
  const want = page.locator(".word-bank").getByRole("button", { name: /想要/ });
  await want.focus();
  await page.keyboard.press("Space");
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("Space");
  await expect(page.locator(".sentence-slot").nth(1)).toContainText("想要");
  await page.locator(".sentence-slot").nth(0).getByRole("button").dragTo(page.locator(".sentence-slot").nth(1), { steps: 10 });
  await expect(page.locator(".sentence-slot").nth(0)).toContainText("想要");
  await expect(page.locator(".sentence-slot").nth(1)).toContainText("我");
});
