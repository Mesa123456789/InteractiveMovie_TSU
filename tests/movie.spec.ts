    expect(choice.frames.find(({ nodes }) => nodes[".media-surface"])!.ms).toBeGreaterThan(choiceLast.ms);
    await expect(page.locator(".media-surface")).toHaveAttribute("data-shot", /^s1b/);

    await page.goto("/");
